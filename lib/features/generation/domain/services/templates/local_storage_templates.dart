import 'package:neat/features/generation/domain/models/field_spec.dart';
import 'package:neat/features/generation/domain/services/templates/dart/_template_utils.dart';
import 'package:neat/features/generation/domain/services/templates/dart/field_codegen.dart';

/// Templates for the `<app>_database` workspace package.
///
/// Emits a self-contained Drift package: its own pubspec (`resolution:
/// workspace`), an [AppDatabase] with a typed table for the witness feature
/// (full local CRUD) plus the Outbox queue when sync is enabled, and a public
/// barrel.
class LocalStorageTemplates {
  LocalStorageTemplates._();

  /// pubspec.yaml for the database package.
  ///
  /// [packageName] is the workspace member name — `<app>_database`, prefixed
  /// like the extracted UI package (unlike core/auth/feature packages).
  /// `resolution: workspace` is required for every member of a Dart workspace.
  static String packagePubspec({required String packageName}) =>
      '''name: $packageName
description: "Offline-first local storage (Drift) — generated by NEAT."
version: 0.1.0
publish_to: 'none'

environment:
  sdk: ^3.12.0
  flutter: ">=1.17.0"

resolution: workspace

dependencies:
  flutter:
    sdk: flutter
  drift: ^2.33.0
  drift_flutter: ^0.3.0

dev_dependencies:
  flutter_lints: ^6.0.0
  build_runner: ^2.4.13
  drift_dev: ^2.33.0
''';

  /// Public entry point (barrel) of the package.
  ///
  /// Re-exports the drift runtime so consumers manipulate rows/queries without
  /// declaring a direct dependency on `drift`.
  static String publicApi({required String packageName}) =>
      '''/// Public API of the $packageName package.
library;

export 'package:drift/drift.dart';

export 'src/database.dart';
''';

  /// build_runner config for the package. Turns off drift_dev's fluent
  /// `db.managers.*` API generation — NEAT's own DAOs never use it, and with
  /// zero tables (no first feature yet) the generated `$AppDatabaseManager`
  /// class ends up with an unused field, which fails the analyze gate.
  static String buildYaml() => '''targets:
  \$default:
    builders:
      drift_dev:
        options:
          generate_manager: false
''';

  /// A typed table for [featureName] (columns from the inferred [fields], keyed
  /// on the String id). Reused by the initial database and by feature-gen
  /// injection. The id stays a non-nullable `TextColumn` primary key.
  static String featureTable(
    String featureName, {
    List<FieldSpec> fields = FieldSpec.idName,
  }) {
    final p = pascal(featureName);
    final columns = fields.map((f) => '  ${f.driftColumnLine()}').join('\n');
    final pk = idField(fields).dartName;
    return '''/// Typed local table for the $featureName feature (full CRUD).
@DataClassName('${p}Row')
class ${p}Rows extends Table {
$columns

  @override
  Set<Column<Object>> get primaryKey => {$pk};
}''';
  }

  /// [featureName]'s table definition as its own file
  /// (`lib/src/table/<featureName>_table.dart`) — one table, one file, the
  /// same convention as [featureDaoFile] (mirrors a real production
  /// monorepo's layout — see ROADMAP.md §5h). `database.dart` only imports +
  /// registers it, and the DAO file imports it directly for its
  /// `@DriftAccessor(tables: [...])` annotation.
  static String featureTableFile(
    String featureName, {
    List<FieldSpec> fields = FieldSpec.idName,
  }) =>
      '''import 'package:drift/drift.dart';

${featureTable(featureName, fields: fields)}
''';

  /// A dedicated `@DriftAccessor` DAO for [featureName]'s table, as its own
  /// file (`lib/src/dao/<featureName>_dao.dart`) — one table, one focused
  /// class, rather than every feature's CRUD methods piling onto `AppDatabase`
  /// itself. `AppDatabase` registers it via `daos: [...]` and exposes it as
  /// `db.${camel(featureName)}Dao` (Drift's standard per-DAO accessor).
  static String featureDaoFile(String featureName) {
    final p = pascal(featureName);
    final acc = '${camel(featureName)}Rows';
    return '''import 'package:drift/drift.dart';

import '../database.dart';
import '../table/${featureName}_table.dart';

part '${featureName}_dao.g.dart';

/// CRUD DAO for the $featureName feature's table.
@DriftAccessor(tables: [${p}Rows])
class ${p}Dao extends DatabaseAccessor<AppDatabase> with _\$${p}DaoMixin {
  ${p}Dao(super.db);

  Future<List<${p}Row>> getAll${p}s() => select($acc).get();

  Future<${p}Row?> get$p(String id) =>
      (select($acc)..where((t) => t.id.equals(id))).getSingleOrNull();

  /// Reactive list (emits on every local write).
  Stream<List<${p}Row>> watch${p}s() => select($acc).watch();

  Future<void> upsert$p(${p}Row row) => into($acc).insertOnConflictUpdate(row);

  Future<void> upsertAll${p}s(List<${p}Row> rows) =>
      batch((b) => b.insertAllOnConflictUpdate($acc, rows));

  Future<void> delete$p(String id) =>
      (delete($acc)..where((t) => t.id.equals(id))).go();
}
''';
  }

  /// The Outbox queue's table definition as its own file
  /// (`lib/src/table/outbox_table.dart`) — same convention as
  /// [featureTableFile].
  static String outboxTableFile() => '''import 'package:drift/drift.dart';

/// Outbox queue: writes made offline are appended here and replayed by the
/// SyncService when connectivity returns.
class OutboxEntries extends Table {
  IntColumn get id => integer().autoIncrement()();
  TextColumn get operation => text()();
  TextColumn get endpoint => text()();
  TextColumn get payload => text().nullable()();
  IntColumn get retryCount => integer().withDefault(const Constant(0))();
  DateTimeColumn get createdAt => dateTime().withDefault(currentDateAndTime)();

  /// When the next retry is due (exponential backoff). Null means "due now".
  DateTimeColumn get nextRetryAt => dateTime().nullable()();

  /// Set by SyncService when the backend reports a conflict (e.g. a 409) —
  /// excluded from ordinary retries until resolved via [OutboxDao.resolveConflict].
  BoolColumn get hasConflict => boolean().withDefault(const Constant(false))();
}
''';

  /// The Outbox queue's dedicated DAO (`lib/src/dao/outbox_dao.dart`) — same
  /// one-table-one-file convention as [featureDaoFile]. `SyncService` and
  /// every offline-first local source reach it via `db.outboxDao`.
  static String outboxDaoFile() => '''import 'package:drift/drift.dart';

import '../database.dart';
import '../table/outbox_table.dart';

part 'outbox_dao.g.dart';

/// DAO for the Outbox queue (offline-write replay — see [OutboxEntries]).
@DriftAccessor(tables: [OutboxEntries])
class OutboxDao extends DatabaseAccessor<AppDatabase> with _\$OutboxDaoMixin {
  OutboxDao(super.db);

  /// Queue a write to be replayed later.
  Future<void> enqueueOutbox({
    required String operation,
    required String endpoint,
    String? payload,
  }) =>
      into(outboxEntries).insert(OutboxEntriesCompanion.insert(
        operation: operation,
        endpoint: endpoint,
        payload: Value(payload),
      ));

  /// Pending writes that aren't flagged as conflicting, oldest first.
  Future<List<OutboxEntry>> pendingOutbox() => (select(outboxEntries)
        ..where((t) => t.hasConflict.equals(false))
        ..orderBy([(t) => OrderingTerm.asc(t.createdAt)]))
      .get();

  /// Watch the pending queue reactively (excludes conflicted entries).
  Stream<List<OutboxEntry>> watchPendingOutbox() =>
      (select(outboxEntries)..where((t) => t.hasConflict.equals(false))).watch();

  Future<void> deleteOutbox(int id) =>
      (delete(outboxEntries)..where((t) => t.id.equals(id))).go();

  /// Bumps the retry counter and persists the next-attempt time (the backoff
  /// delay itself is computed by SyncService, not here).
  Future<void> incrementRetry(int id, {DateTime? nextRetryAt}) async {
    final row =
        await (select(outboxEntries)..where((t) => t.id.equals(id))).getSingleOrNull();
    if (row == null) return;
    await (update(outboxEntries)..where((t) => t.id.equals(id))).write(
      OutboxEntriesCompanion(
        retryCount: Value(row.retryCount + 1),
        nextRetryAt: Value(nextRetryAt),
      ),
    );
  }

  /// Flags an entry as conflicting — excluded from [pendingOutbox] until
  /// resolved.
  Future<void> markConflict(int id) =>
      (update(outboxEntries)..where((t) => t.id.equals(id)))
          .write(const OutboxEntriesCompanion(hasConflict: Value(true)));

  /// Conflicting writes awaiting app-level resolution.
  Future<List<OutboxEntry>> conflictedOutbox() =>
      (select(outboxEntries)..where((t) => t.hasConflict.equals(true))).get();

  /// Resolves a conflicted entry: [retry] re-queues it (clears the flag,
  /// resets the backoff) for another attempt; otherwise it's discarded (e.g.
  /// the app chose to keep the server's version).
  Future<void> resolveConflict(int id, {required bool retry}) => retry
      ? (update(outboxEntries)..where((t) => t.id.equals(id))).write(
          const OutboxEntriesCompanion(
            hasConflict: Value(false),
            retryCount: Value(0),
            nextRetryAt: Value(null),
          ),
        )
      : deleteOutbox(id);
}
''';

  /// The Drift database. Carries a typed table for the witness [featureName]
  /// (full local CRUD); when [withOutbox] is true it also carries the Outbox
  /// queue table + helpers for the sync strategy. Every table and DAO lives in
  /// its own file (see [featureTableFile]/[featureDaoFile]) — `database.dart`
  /// only imports + registers them. Anchors (`// neat:…`) let feature-gen
  /// inject new tables / DAOs later.
  ///
  /// [isWeb] (project targets web): `drift_flutter`'s `driftDatabase()` throws
  /// `Invalid argument(s): When compiling to the web, the \`web\` parameter
  /// needs to be set.` unless a `DriftWebOptions` is passed — found running a
  /// real offline-first + web project in Chrome (every provider downstream of
  /// `appDatabaseProvider` failed in cascade). `_open()` branches on `kIsWeb`
  /// to supply it; see [driftWebSetupDoc] for the two files (`sqlite3.wasm`,
  /// `drift_worker.dart.js`) this still needs manually in `web/` — they're
  /// prebuilt release binaries, not something a string template can emit.
  static String database({
    required String featureName,
    bool withOutbox = false,
    bool includeFirstTable = true,
    List<FieldSpec> fields = FieldSpec.idName,
    bool isWeb = false,
  }) {
    final p = pascal(featureName);

    final tableEntries = StringBuffer();
    if (includeFirstTable) tableEntries.write('    ${p}Rows,\n');
    if (withOutbox) tableEntries.write('    OutboxEntries,\n');
    tableEntries.write('    // neat:table-names');

    // One table definition, one file (see [featureTableFile]/
    // [outboxTableFile]) — `database.dart` only imports + registers them.
    final tableImports = StringBuffer();
    if (includeFirstTable) {
      tableImports.writeln("import 'table/${featureName}_table.dart';");
    }
    if (withOutbox) tableImports.writeln("import 'table/outbox_table.dart';");
    tableImports.write('// neat:table-imports');

    // One `@DriftAccessor` DAO file per table (see [featureDaoFile]/
    // [outboxDaoFile]) — `AppDatabase` only imports + registers them, it
    // never carries their query methods itself.
    final daoImports = StringBuffer();
    if (includeFirstTable) {
      daoImports.writeln("import 'dao/${featureName}_dao.dart';");
    }
    if (withOutbox) daoImports.writeln("import 'dao/outbox_dao.dart';");
    daoImports.write('// neat:dao-imports');

    final daoEntries = StringBuffer();
    if (includeFirstTable) daoEntries.write('    ${p}Dao,\n');
    if (withOutbox) daoEntries.write('    OutboxDao,\n');
    daoEntries.write('    // neat:daos');

    final webImport = isWeb
        ? "import 'package:flutter/foundation.dart' show kIsWeb;\n"
        : '';

    return '''import 'package:drift/drift.dart';
import 'package:drift_flutter/drift_flutter.dart';
$webImport
$tableImports
$daoImports

part 'database.g.dart';

@DriftDatabase(
  tables: [
${tableEntries.toString()}
  ],
  daos: [
${daoEntries.toString()}
  ],
)
class AppDatabase extends _\$AppDatabase {
  AppDatabase([QueryExecutor? executor]) : super(executor ?? _open());

  @override
  int get schemaVersion => 1;

  // A table added later (Workshop feature-gen) bumps schemaVersion and
  // inserts its own `if (from < N) await m.createTable(...)` step here —
  // otherwise a device that already has the app installed keeps its old
  // on-disk schema forever (Drift only runs onCreate on a brand-new database
  // file, never onUpgrade, unless the version actually changes).
  @override
  MigrationStrategy get migration => MigrationStrategy(
        onCreate: (m) => m.createAll(),
        onUpgrade: (m, from, to) async {
          // neat:migrations
        },
        beforeOpen: (details) async {
          // A downgrade (e.g. a beta tester reinstalling an older build) puts
          // an on-disk schema version the app's own migration steps have
          // never seen — replaying onUpgrade from there isn't safe. Detect it
          // and drop + recreate everything rather than risk a crash on an
          // unrecognized schema.
          if (details.hadUpgrade &&
              details.versionBefore != null &&
              details.versionBefore! > schemaVersion) {
            await customStatement('PRAGMA foreign_keys = OFF');
            for (final table in allTables) {
              await customStatement('DROP TABLE IF EXISTS \${table.actualTableName}');
            }
            await customStatement('PRAGMA foreign_keys = ON');
            await customStatement('PRAGMA user_version = 0');
            await createMigrator().createAll();
          }
        },
      );

  ${isWeb ? _webOpen : "static QueryExecutor _open() => driftDatabase(name: 'app_db');"}
}
''';
  }

  /// [database]'s web-aware `_open()` — native platforms fall through to the
  /// same one-liner as before; web needs the two files [driftWebSetupDoc]
  /// documents (`sqlite3.wasm`, `drift_worker.dart.js`, served from `web/`).
  static const String _webOpen = '''static QueryExecutor _open() {
    if (kIsWeb) {
      return driftDatabase(
        name: 'app_db',
        web: DriftWebOptions(
          sqlite3Wasm: Uri.parse('sqlite3.wasm'),
          driftWorker: Uri.parse('drift_worker.dart.js'),
        ),
      );
    }
    return driftDatabase(name: 'app_db');
  }''';
}
